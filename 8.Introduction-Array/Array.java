public class Array{
    public static void main(String[] args){
        int[] rollNo = new int[3];
        //101, 102, 103

        rollNo[0] = 101;
        rollNo[1] = 102;
        rollNo[2] = 103;

        System.out.println(rollNo[0]);
        System.out.println(rollNo[1]);
        System.out.println(rollNo[2]);

        System.out.println(rollNo.length);
    }
}